#!/usr/bin/env bash
set -euo pipefail

if [[ $# -gt 1 || ( $# -eq 1 && "$1" != --check ) ]]; then
    printf 'Usage: %s [--check]\n' "${0##*/}" >&2
    exit 1
fi

project_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
output="$project_dir/beginnix.sh"
bundle=$(mktemp "$project_dir/.beginnix-build.XXXXXX")
trap 'rm -f -- "$bundle"' EXIT

{
    printf '#!/usr/bin/env bash\n'
    printf '# Generated by build.sh from src/. Edit the source files and rebuild.\n\n'
    for module in engine course challenges grading; do
        cat -- "$project_dir/src/$module.sh"
        printf '\n'
    done
    printf 'main "$@"\n'
} > "$bundle"
bash -n "$bundle"

if [[ "${1:-}" == --check ]]; then
    if ! cmp -s -- "$bundle" "$output"; then
        printf 'Run ./build.sh to update beginnix.sh.\n' >&2
        exit 1
    fi
    printf 'beginnix.sh matches the source.\n'
else
    chmod 755 "$bundle"
    mv -fT -- "$bundle" "$output"
    printf 'Built %s\n' "$output"
fi
